"""System tables: CommunicationLog, SyncOperation, AuditLog."""
from ..extensions import db
from ..utils.helpers import utcnow


class CommunicationLog(db.Model):
    """One row per API request. Used by the Network Monitoring dashboard.

    Privacy: only the URL *pattern* (e.g. /api/visitors/<public_id>) is stored,
    never query strings, bodies, passwords, session cookies or QR tokens.
    """

    __tablename__ = "communication_logs"

    id = db.Column(db.Integer, primary_key=True)
    timestamp = db.Column(db.DateTime, nullable=False, default=utcnow, index=True)
    device_id = db.Column(db.String(64), nullable=False, index=True)
    client_ip = db.Column(db.String(45))
    network_type = db.Column(db.String(8))  # LAN | WAN | UNKNOWN
    endpoint = db.Column(db.String(160), nullable=False, index=True)
    method = db.Column(db.String(8), nullable=False)
    status_code = db.Column(db.Integer, nullable=False, index=True)
    duration_ms = db.Column(db.Float, nullable=False)
    success = db.Column(db.Boolean, nullable=False)
    request_bytes = db.Column(db.Integer, default=0)
    response_bytes = db.Column(db.Integer, default=0)
    is_secure = db.Column(db.Boolean, default=False)  # was the request over HTTPS/TLS?


class SyncOperation(db.Model):
    """Server-side record of every scan operation (online retry-safe & offline sync).

    `operation_id` is generated by the client and is UNIQUE.  If the same id
    arrives twice, the server returns the stored result instead of repeating
    the action - this is called idempotency.
    The raw QR token is never stored, only its hash.
    """

    __tablename__ = "sync_operations"
    __table_args__ = (
        db.CheckConstraint("status IN ('PENDING','SUCCESS','FAILED')", name="ck_sync_status"),
    )

    id = db.Column(db.Integer, primary_key=True)
    operation_id = db.Column(db.String(64), unique=True, nullable=False, index=True)
    device_id = db.Column(db.String(64), nullable=False, index=True)
    staff_id = db.Column(db.Integer, db.ForeignKey("security_staff.id"), nullable=False)
    op_type = db.Column(db.String(10), nullable=False)  # check-in | check-out
    token_hash = db.Column(db.String(64), nullable=False)
    channel = db.Column(db.String(8), nullable=False, default="sync")  # sync | online
    status = db.Column(db.String(8), nullable=False, default="PENDING", index=True)
    result_code = db.Column(db.String(24))
    result_json = db.Column(db.Text)  # {"ok":..,"code":..,"message":..,"visitor_id":..} no PII
    client_created_at = db.Column(db.DateTime)
    received_at = db.Column(db.DateTime, nullable=False, default=utcnow, index=True)
    processed_at = db.Column(db.DateTime)


class AuditLog(db.Model):
    __tablename__ = "audit_logs"

    id = db.Column(db.Integer, primary_key=True)
    timestamp = db.Column(db.DateTime, nullable=False, default=utcnow, index=True)
    actor_type = db.Column(db.String(12), nullable=False)  # admin|security|host|visitor|system
    actor_id = db.Column(db.Integer)
    action = db.Column(db.String(48), nullable=False, index=True)
    entity_type = db.Column(db.String(24))
    entity_id = db.Column(db.String(40))
    details = db.Column(db.String(500))
    ip_address = db.Column(db.String(45))
